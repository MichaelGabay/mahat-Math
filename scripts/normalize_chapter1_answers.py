# 5.x — read current files to paste exact content (already normalized)
for name in (
    "5.1_שבר_אלגברי_תחום_הצבה_וצמצום.md",
    "5.2_כפל_וחילוק_שברים_אלגבריים.md",
    "5.3_חיבור_וחיסור_שברים_אלגבריים.md",
):
    text = (BASE / name).read_text(encoding="utf-8")
    s = text.index("<details>")
    e = text.index("</details>")
    inner = text[s + len("<details>") : e].strip()
    inner = inner.removeprefix("<summary>תשובות סופיות</summary>").strip()
    ANSWERS[name] = inner


def patch_file(path: Path, inner: str) -> None:
    text = path.read_text(encoding="utf-8")
    start = text.index("<details>")
    end = text.index("</details>") + len("</details>")
    block = "<details>\n<summary>תשובות סופיות</summary>\n" + inner + "\n</details>"
    path.write_text(text[:start] + block + text[end:], encoding="utf-8")


def main() -> None:
    for fname, inner in sorted(ANSWERS.items()):
        patch_file(BASE / fname, inner)
        print("patched", fname)


if __name__ == "__main__":
    main()
