# Build set of (subtopic, exercise) pairs that have generated graphs
GENERATED = {(d['sub'], d['ex']) for d in E}


def update_markdown(sub_num):
    filename = SUBTOPIC_FILES[sub_num]
    filepath = os.path.join(CHAPTER_DIR, filename)

    with open(filepath, 'r', encoding='utf-8') as f:
        lines = f.readlines()

    new_lines = []
    current_ex = None
    in_answers = False
    i = 0

    while i < len(lines):
        line = lines[i]

        # Stop replacing once we reach the answers block
        if '<details>' in line:
            in_answers = True

        # Detect exercise number  **N.**
        ex_match = re.match(r'\*\*(\d+)\.\*\*', line.strip())
        if ex_match:
            current_ex = int(ex_match.group(1))

        # If line is a table row and we should replace it
        if (not in_answers
                and line.startswith('|')
                and current_ex is not None
                and (sub_num, current_ex) in GENERATED):

            # Consume all consecutive table lines
            while i < len(lines) and lines[i].startswith('|'):
                i += 1

            img_name = f"3_{sub_num}_ex{current_ex:02d}.png"
            new_lines.append(f'![גרף תרגיל {current_ex}](images/{img_name})\n')
            new_lines.append('\n')
            continue

        new_lines.append(line)
        i += 1

    with open(filepath, 'w', encoding='utf-8') as f:
        f.writelines(new_lines)
    print(f"  ✓ Updated: {filename}")


def run_update_markdowns():
    print("\nUpdating markdown files...")
    for sub_num in SUBTOPIC_FILES:
        update_markdown(sub_num)
    print("✓ All markdown files updated.")


