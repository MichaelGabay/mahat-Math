# ── Graph generator ──────────────────────────────────────────────────────────
def make_graph(fname, title, xl, yl, x, y,
               x2=None, y2=None, lbl1=None, lbl2=None,
               time_x=False, bar=False):
    fig, ax = plt.subplots(figsize=(7, 4))
    fig.patch.set_facecolor('white')

    # Fix Hebrew RTL for all string x-tick labels
    def fix_xlabels(labels):
        return [h(lbl) if isinstance(lbl, str) else lbl for lbl in labels]

    if bar:
        if x2 is not None and y2 is not None:
            offset = np.arange(len(x))
            ax.bar(offset - 0.2, y,  0.4, color='steelblue', alpha=0.85, label=h(lbl1), zorder=3)
            ax.bar(offset + 0.2, y2, 0.4, color='tomato',    alpha=0.85, label=h(lbl2), zorder=3)
            ax.set_xticks(offset); ax.set_xticklabels(fix_xlabels(x))
            ax.legend()
        else:
            ax.bar(x if not all(isinstance(v, str) for v in x) else range(len(x)),
                   y, color='steelblue', alpha=0.85, zorder=3)
            if all(isinstance(v, str) for v in x):
                ax.set_xticks(range(len(x)))
                ax.set_xticklabels(fix_xlabels(x))
    else:
        ax.plot(x, y, 'b-o', lw=2, ms=5, label=h(lbl1) if lbl1 else None, zorder=3)
        if x2 is not None and y2 is not None:
            ax.plot(x2, y2, 'r-s', lw=2, ms=5, label=h(lbl2) if lbl2 else None, zorder=3)
            ax.legend(fontsize=9)

    ax.set_title(h(title), fontsize=12, fontweight='bold', pad=8)
    ax.set_xlabel(h(xl), fontsize=10)
    ax.set_ylabel(h(yl), fontsize=10)
    ax.grid(True, alpha=0.3, zorder=0)

    if time_x:
        def fmt_time(v, _):
            hh = int(v); m = round((v - hh) * 60)
            return f'{hh}:{m:02d}'
        ax.xaxis.set_major_formatter(ticker.FuncFormatter(fmt_time))
        ticks = sorted(set(list(x) + (list(x2) if x2 else [])))
        ax.set_xticks(ticks)
        ax.tick_params(axis='x', rotation=45, labelsize=8)

    plt.tight_layout()
    path = os.path.join(IMAGES_DIR, fname)
    plt.savefig(path, dpi=150, bbox_inches='tight', facecolor='white')
    plt.close()


